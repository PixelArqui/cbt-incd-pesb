  async loadAllData() {
    this.setLoading(true);
    try {
      const muniPromises = MUNICIPIOS.map(m => APIService.fetchWeather(m.lat, m.lon, m.nome).then(d => { if(d) this.weatherData[m.nome] = d; }));
      const distPromises = DISTRITOS.map(d => APIService.fetchWeather(d.lat, d.lon, d.nome).then(data => { if(data) this.weatherData[d.nome] = data; }));
      
      await Promise.all([...muniPromises, ...distPromises]);
      this.fireData = await APIService.fetchFires();
      
      this.updateUI();
      const now = new Date();
      document.getElementById('lastUpdate').textContent = `Atualizado: ${now.toLocaleTimeString('pt-BR', {hour:'2-digit',minute:'2-digit'})}`;
      
    } catch (error) {
      console.error("Erro ao carregar dados:", error);
    } finally {
      this.setLoading(false);
    }
  }

  updateUI() {
    this.renderCards('muniCards', MUNICIPIOS);
    this.renderCards('distritoCards', DISTRITOS);
    this.updateGauges();
    this.updateFireMarkers();
  }

  renderCards(containerId, locations) {
    const container = document.getElementById(containerId);
    if (!container) return;
    container.innerHTML = '';
    
    locations.forEach(loc => {
      const d = this.weatherData[loc.nome];
      if (!d) return;
      
      const risco = RiskCalculator.calcularRisco(d.temp, d.umidade, d.vento);
      const c = RiskCalculator.getRiskColor(risco);
      
      const card = document.createElement('div');
      card.className = 'muni-card';
      card.innerHTML = `
        <div class="muni-card-header">
          <span class="muni-name">${loc.nome}</span>
          <span class="muni-risk-badge" style="background:${c.bg};color:${c.text}">${c.label}</span>
        </div>
        <div class="muni-metrics">
          <div class="metric"><div class="metric-value" style="color:${d.temp>30?'#f97316':'#e2e8f0'}">${d.temp.toFixed(1)}C</div><div class="metric-label">Temp</div></div>
          <div class="metric"><div class="metric-value" style="color:${d.umidade<30?'#dc2626':'#e2e8f0'}">${d.umidade}%</div><div class="metric-label">Umidade</div></div>
          <div class="metric"><div class="metric-value" style="color:${d.vento>30?'#dc2626':'#e2e8f0'}">${d.vento.toFixed(1)}</div><div class="metric-label">Vento</div></div>
          <div class="metric"><div class="metric-value" style="color:#f97316">${d.diasSemChuva}</div><div class="metric-label">Dias secos</div></div>
        </div>
      `;
      card.addEventListener('click', () => this.map.setView([loc.lat, loc.lon], 13));
      container.appendChild(card);
    });
  }

  updateGauges() {
    let totalRisco = 0, totalFMA = 0, count = 0;
    
    [...MUNICIPIOS, ...DISTRITOS].forEach(loc => {
      const d = this.weatherData[loc.nome];
      if (d) {
        totalRisco += RiskCalculator.calcularRisco(d.temp, d.umidade, d.vento);
        totalFMA += d.fma;
        count++;
      }
    });

    const riscoMedio = count > 0 ? totalRisco / count : 0;
    const fmaMedio = count > 0 ? totalFMA / count : 0;

    const riskColor = RiskCalculator.getRiskColor(riscoMedio);
    document.getElementById('gaugeNeedle').style.transform = `translateX(-50%) rotate(${-90 + (riscoMedio/100)*180}deg)`;
    document.getElementById('gaugeValue').textContent = `${Math.round(riscoMedio)}%`;
    document.getElementById('gaugeValue').style.color = riskColor.bg;
    document.getElementById('gaugeLabel').textContent = `Risco ${riskColor.label}`;

    const fmaColor = RiskCalculator.getFMAColor(fmaMedio <= 1 ? 'Nulo' : fmaMedio <= 3 ? 'Pequeno' : fmaMedio <= 8 ? 'Medio' : fmaMedio <= 24 ? 'Alto' : 'Muito Alto');
    const fmaPct = Math.min(100, (fmaMedio/30)*100);
    document.getElementById('fmaGaugeNeedle').style.transform = `translateX(-50%) rotate(${-90 + (fmaPct/100)*180}deg)`;
    document.getElementById('fmaGaugeValue').textContent = fmaMedio.toFixed(1);
    document.getElementById('fmaGaugeValue').style.color = fmaColor.bg;
  }

  updateFireMarkers() {
    this.fireMarkers.forEach(m => this.map.removeLayer(m));
    this.fireMarkers = [];
    
    this.fireData.forEach(f => {
      const radius = Math.max(4, Math.min(14, f.frp / 2));
      const marker = L.circleMarker([f.lat, f.lon], {radius, fillColor:'#f97316', color:'#dc2626', weight:1.5, fillOpacity:0.7}).addTo(this.map);
      marker.bindPopup(`<div class="popup-content"><div class="popup-title">Foco de Calor</div><div>FRP: ${f.frp.toFixed(1)} MW</div></div>`);
      this.fireMarkers.push(marker);
    });

    document.getElementById('fireCount').textContent = this.fireData.length;
    document.getElementById('fireFrp').textContent = this.fireData.length > 0 ? (this.fireData.reduce((s,f)=>s+f.frp,0)/this.fireData.length).toFixed(1) : '0.0';
  }

  setLoading(isLoading) {
    const btn = document.getElementById('refreshBtn');
    const overlay = document.getElementById('loadingOverlay');
    if (isLoading) {
      btn?.classList.add('loading');
      overlay?.classList.remove('hidden');
    } else {
      btn?.classList.remove('loading');
      overlay?.classList.add('hidden');
    }
  }
