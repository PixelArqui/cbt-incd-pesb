/**
 * Utilitários e Cálculos Matemáticos
 */
class RiskCalculator {
  static calcularRisco(temp, umidade, vento) {
    let risco = 0;
    if (umidade < 30) risco += 35; else if (umidade < 50) risco += 20; else if (umidade < 70) risco += 10;
    if (temp > 30) risco += 35; else if (temp > 25) risco += 20; else if (temp > 20) risco += 10;
    if (vento > 30) risco += 30; else if (vento > 20) risco += 15; else if (vento > 10) risco += 5;
    if (umidade < 30 && temp > 30 && vento > 30) risco = 100;
    return Math.min(risco, 100);
  }

  static getRiskColor(risco) {
    if (risco >= 85) return { bg: '#dc2626', text: '#fff', label: 'EXTREMO' };
    if (risco >= 60) return { bg: '#f97316', text: '#fff', label: 'ALTO' };
    if (risco >= 35) return { bg: '#eab308', text: '#000', label: 'MÉDIO' };
    return { bg: '#22c55e', text: '#fff', label: 'BAIXO' };
  }

  static getFMAColor(classe) {
    switch(classe) {
      case 'Nulo': return {bg:'#2563eb',text:'#fff'};
      case 'Pequeno': return {bg:'#22c55e',text:'#fff'};
      case 'Medio': return {bg:'#eab308',text:'#000'};
      case 'Alto': return {bg:'#f97316',text:'#fff'};
      case 'Muito Alto': return {bg:'#dc2626',text:'#fff'};
      default: return {bg:'#64748b',text:'#fff'};
    }
  }

  static calcularFMA(ur13h, chuva24h, fmaOntem) {
    let y;
    if(ur13h >= 85) y = 0.0;
    else if(ur13h >= 55) y = (100.0 - ur13h) / 10.0;
    else if(ur13h >= 30) y = (100.0 - ur13h) / 5.0;
    else y = (100.0 - ur13h) / 2.5;
    
    let fmaHoje;
    if(chuva24h <= 2.4) fmaHoje = fmaOntem + y;
    else if(chuva24h <= 4.9) fmaHoje = Math.max(0.0, fmaOntem - chuva24h) + y;
    else if(chuva24h <= 9.9) fmaHoje = (fmaOntem * 0.7) + y;
    else fmaHoje = y;
    
    let classe = fmaHoje <= 1.0 ? 'Nulo' : fmaHoje <= 3.0 ? 'Pequeno' : fmaHoje <= 8.0 ? 'Medio' : fmaHoje <= 24.0 ? 'Alto' : 'Muito Alto';
    return { fma: Math.round(fmaHoje * 100) / 100, classe };
  }
}

/**
 * Serviços Externos (APIs e Cache)
 */
class APIService {
  static getCached(key) {
    try { return JSON.parse(localStorage.getItem(key)); } catch(e) { return null; }
  }
  static setCache(key, val) {
    try { localStorage.setItem(key, JSON.stringify(val)); } catch(e) {}
  }

  static async fetchWeather(lat, lon, nome) {
    if (!navigator.onLine) return this.getCached('weather_' + nome);
    
    const url = `https://api.open-meteo.com/v1/forecast?latitude=${lat}&longitude=${lon}&hourly=relative_humidity_2m&daily=precipitation_sum&current=temperature_2m,relative_humidity_2m,wind_speed_10m,wind_direction_10m&timezone=America/Sao_Paulo&forecast_days=7`;
    try {
      const res = await fetch(url);
      const data = await res.json();
      const ur13h = data.hourly.relative_humidity_2m[13];
      const chuva24h = data.daily.precipitation_sum[0];
      let diasSemChuva = 0;
      for (let p of data.daily.precipitation_sum) { if (p < 2.5) diasSemChuva++; else break; }
      
      const fmaResult = RiskCalculator.calcularFMA(ur13h, chuva24h, 0);
      const result = {
        temp: data.current.temperature_2m,
        umidade: data.current.relative_humidity_2m,
        vento: data.current.wind_speed_10m,
        ventoDir: data.current.wind_direction_10m,
        diasSemChuva,
        fma: fmaResult.fma,
        fmaClasse: fmaResult.classe
      };
      this.setCache('weather_' + nome, result);
      return result;
    } catch (e) {
      console.warn('Usando cache para o clima:', e);
      return this.getCached('weather_' + nome);
    }
  }

  static async fetchFires() {
    if (!navigator.onLine) return this.getCached('firms_data') || [];
    const url = `https://firms.modaps.eosdis.nasa.gov/api/area/csv/${MAP_KEY}/VIIRS_NOAA20_NRT/-42.7,-21.3,-42.1,-20.4/1`;
    try {
      const res = await fetch(url);
      const text = await res.text();
      const lines = text.trim().split('\n');
      if(lines.length < 2) return [];
      
      const headers = lines[0].split(',');
      const latIdx = headers.indexOf('latitude');
      const lonIdx = headers.indexOf('longitude');
      const frpIdx = headers.indexOf('frp');
      const confIdx = headers.indexOf('confidence');
      
      const fires = lines.slice(1).map(line => {
        const cols = line.split(',');
        return { lat: parseFloat(cols[latIdx]), lon: parseFloat(cols[lonIdx]), frp: parseFloat(cols[frpIdx]) || 0, confidence: cols[confIdx] || 'n/a' };
      }).filter(f => !isNaN(f.lat) && !isNaN(f.lon));
      
      this.setCache('firms_data', fires);
      return fires;
    } catch (e) {
      return this.getCached('firms_data') || [];
    }
  }
}

